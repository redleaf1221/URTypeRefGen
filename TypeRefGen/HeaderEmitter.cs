using System.Text;

namespace TypeRefGen;

/// <summary>
/// Renders the selected types as a URKit header: one <c>TypeRef</c> constant per
/// type plus an optional wrapper exposing only the members that can be
/// marshalled safely. Unsupported members are reported, never guessed.
/// </summary>
internal sealed class HeaderEmitter {
    private readonly Options _o;
    private readonly TypeMapper _map;
    private readonly TextWriter _report;
    private readonly List<string> _selfCheckDecls = new();
    private readonly List<string> _selfCheckCalls = new();
    private readonly HashSet<string> _usedWrappers = new(StringComparer.Ordinal);

    public HeaderEmitter(Options options, TypeMapper map, TextWriter report) {
        _o = options;
        _map = map;
        _report = report;
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private string WrapperName(TypeRecord t) {
        var baseName = TypeMapper.SafeIdentifier(t.Name);
        if (!string.IsNullOrEmpty(t.Namespace))
            baseName += "_" + TypeMapper.SafeIdentifier(t.Namespace);
        var candidate = baseName;
        if (_usedWrappers.Contains(candidate))
            candidate = baseName + "_" + TypeMapper.SafeIdentifier(t.Image);
        var unique = candidate;
        var index = 2;
        while (!_usedWrappers.Add(unique))
            unique = candidate + "_" + index++;
        return unique;
    }

    public string Emit(IReadOnlyList<TypeRecord> selected) {
        var sb = new StringBuilder(64 * 1024);
        sb.AppendLine("// AUTO-GENERATED by URTypeRefGen - do not edit; regenerate instead.");
        sb.AppendLine("//");
        sb.AppendLine($"//   input     : {_o.DllDir}");
        sb.AppendLine($"//   assemblies: {string.Join(", ", _o.Assemblies.Count > 0 ? _o.Assemblies : new List<string> { "(all)" })}");
        sb.AppendLine($"//   types     : {selected.Count}");
        sb.AppendLine("//");
        sb.AppendLine("// TypeRef is the runtime lookup triplet (image, namespace, type).");
        sb.AppendLine("// Wrappers expose only members whose type maps safely; the rest is listed");
        sb.AppendLine("// in the report so nothing fails silently at run time.");
        sb.AppendLine();
        sb.AppendLine("#pragma once");
        sb.AppendLine();
        sb.AppendLine("#include <cstdint>");
        sb.AppendLine("#include <string>");
        sb.AppendLine("#include <string_view>");
        sb.AppendLine("#include <vector>");
        sb.AppendLine();
        sb.AppendLine("#include \"sdk/unity/unity.h\"");
        sb.AppendLine();
        sb.AppendLine($"namespace {_o.Namespace} {{");
        sb.AppendLine();
        sb.AppendLine("using TypeRef = ::URK::Unity::TypeRef;");
        sb.AppendLine("using Object = ::URK::Unity::Object;");
        sb.AppendLine();

        // Enums first: a field or property can reference one, so every enum type
        // has to be declared before the wrappers that use it.
        foreach (var t in selected.Where(t => t.IsEnum))
            EmitEnum(sb, t);
        foreach (var t in selected.Where(t => !t.IsEnum && t.IsValueType))
            EmitValueType(sb, t);
        foreach (var t in selected.Where(t => !t.IsEnum && !t.IsValueType && !t.IsInterface))
            EmitClass(sb, t);

        EmitSelfCheck(sb);
        sb.AppendLine($"}} // namespace {_o.Namespace}");
        return sb.ToString();
    }

    private void EmitEnum(StringBuilder sb, TypeRecord t) {
        var flat = TypeMapper.EnumCppName(t);
        var underlying = _map.UnderlyingCpp(t);
        sb.AppendLine($"// enum {t.DisplayName}  [{t.Image}]");
        sb.AppendLine($"inline constexpr TypeRef k{flat}{{\"{Escape(t.Image)}\", \"{Escape(t.Namespace)}\", \"{Escape(t.Name)}\"}};");
        sb.AppendLine($"enum class {flat} : {underlying} {{");
        foreach (var (name, value) in t.EnumValues) {
            var member = TypeMapper.SafeIdentifier(name);
            if (member.EndsWith('_'))
                member = member[..^1];
            sb.AppendLine($"    {member} = {value},");
        }
        sb.AppendLine("};");
        sb.AppendLine();
        _report.WriteLine($"{t.DisplayName}\timage={t.Image}\tenum {flat}\tvalues={t.EnumValues.Count}");
    }

    private void EmitValueType(StringBuilder sb, TypeRecord t) {
        sb.AppendLine($"// struct {t.DisplayName}  [{t.Image}]");
        sb.AppendLine("// Value type: no object handle exists, so only the TypeRef is emitted.");
        sb.AppendLine($"inline constexpr TypeRef k{WrapperName(t)}{{\"{Escape(t.Image)}\", \"{Escape(t.Namespace)}\", \"{Escape(t.Name)}\"}};");
        sb.AppendLine();
        _report.WriteLine($"{t.DisplayName}\timage={t.Image}\tstruct\t(value type: TypeRef only)");
    }

    private void EmitClass(StringBuilder sb, TypeRecord t) {
        var wrapper = WrapperName(t);
        var refName = "k" + wrapper;
        var isUnityObject = _map.DerivesFromUnityObject(t);
        var variable = "v_" + wrapper;
        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        var emitted = 0;
        var skipped = new List<string>();

        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine($"// {t.DisplayName}  [{t.Image}]{(isUnityObject ? "  (UnityEngine.Object)" : "")}");
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine($"inline constexpr TypeRef {refName}{{\"{Escape(t.Image)}\", \"{Escape(t.Namespace)}\", \"{Escape(t.Name)}\"}};");
        sb.AppendLine();
        sb.AppendLine($"struct {wrapper} {{");
        sb.AppendLine($"    static constexpr TypeRef type() {{ return {refName}; }}");
        sb.AppendLine();
        sb.AppendLine("    Object o;");
        sb.AppendLine($"    {wrapper}() = default;");
        sb.AppendLine($"    explicit {wrapper}(Object value) : o(value) {{}}");
        sb.AppendLine("    explicit operator bool() const { return static_cast<bool>(o); }");
        sb.AppendLine("    void *handle() const { return o.handle(); }");
        _selfCheckDecls.Add($"{wrapper} {variable}{{}};");

        if (_o.Fields) {
            foreach (var f in t.Fields) {
                var member = UniqueMember(usedNames, f.Name);
                var cpp = _map.Map(f.Type);
                if (cpp is null) {
                    skipped.Add($"field {f.Name} : {TypeMapper.ShortType(f.Type)}");
                    continue;
                }
                sb.AppendLine();
                sb.AppendLine($"    // field: {TypeMapper.ShortType(f.Type)}{(f.IsStatic ? " (static)" : "")}");
                if (f.IsStatic) {
                    sb.AppendLine($"    static {cpp} {member}() {{ return Object::StaticGetField<{cpp}>({refName}, \"{Escape(f.Name)}\"); }}");
                    if (CanWriteCpp(cpp))
                        sb.AppendLine($"    static void set_{member}({cpp} value) {{ Object::StaticSetField<{cpp}>({refName}, \"{Escape(f.Name)}\", value); }}");
                    _selfCheckCalls.Add($"(void){wrapper}::{member}();");
                    if (CanWriteCpp(cpp))
                        _selfCheckCalls.Add($"{wrapper}::set_{member}({cpp}{{}});");
                } else {
                    sb.AppendLine($"    {cpp} {member}() const {{ return o.GetField<{cpp}>(\"{Escape(f.Name)}\"); }}");
                    if (CanWriteCpp(cpp))
                        sb.AppendLine($"    void set_{member}({cpp} value) {{ o.SetField<{cpp}>(\"{Escape(f.Name)}\", value); }}");
                    _selfCheckCalls.Add($"(void){variable}.{member}();");
                    if (CanWriteCpp(cpp))
                        _selfCheckCalls.Add($"{variable}.set_{member}({cpp}{{}});");
                }
                emitted++;
            }
        }

        if (_o.Properties) {
            foreach (var p in t.Properties) {
                var member = UniqueMember(usedNames, p.Name);
                var cpp = _map.Map(p.Type);
                if (cpp is null) {
                    skipped.Add($"property {p.Name} : {TypeMapper.ShortType(p.Type)}");
                    continue;
                }
                sb.AppendLine();
                sb.AppendLine($"    // property: {TypeMapper.ShortType(p.Type)}{(p.IsStatic ? " (static)" : "")}");
                if (p.IsStatic) {
                    if (p.CanRead) {
                        sb.AppendLine($"    static {cpp} {member}() {{ return ::URK::Unity::detail::InvokeStatic<{cpp}>({refName}, \"get_{Escape(p.Name)}\"); }}");
                        _selfCheckCalls.Add($"(void){wrapper}::{member}();");
                    }
                    if (p.CanWrite) {
                        sb.AppendLine($"    static void set_{member}({cpp} value) {{ ::URK::Unity::detail::InvokeStatic<void>({refName}, \"set_{Escape(p.Name)}\", value); }}");
                        _selfCheckCalls.Add($"{wrapper}::set_{member}({cpp}{{}});");
                    }
                } else {
                    if (p.CanRead) {
                        sb.AppendLine($"    {cpp} {member}() const {{ return o.GetProperty<{cpp}>(\"{Escape(p.Name)}\"); }}");
                        _selfCheckCalls.Add($"(void){variable}.{member}();");
                    }
                    if (p.CanWrite) {
                        sb.AppendLine($"    void set_{member}({cpp} value) {{ o.SetProperty(\"{Escape(p.Name)}\", value); }}");
                        _selfCheckCalls.Add($"{variable}.set_{member}({cpp}{{}});");
                    }
                }
                emitted++;
            }
        }

        if (_o.Methods) {
            // Call<Ret> resolves overloads by argument count only, so same-name
            // same-arity groups are either emitted through CallExact (which passes
            // the real parameter type names) or skipped with a report entry.
            var arityGroups = t.Methods
                .GroupBy(m => (m.Name, Arity: m.Params.Count))
                .ToDictionary(g => g.Key, g => g.Count());

            foreach (var m in t.Methods) {
                var member = UniqueMember(usedNames, m.Name);
                var ret = _map.Map(m.Type);
                var parameters = new List<string>();
                var ok = ret is not null;
                foreach (var (paramType, paramName) in m.Params) {
                    var mapped = _map.Map(paramType);
                    if (mapped is null) {
                        ok = false;
                        break;
                    }
                    parameters.Add($"{(mapped == "std::string" ? "std::string_view" : mapped)} {TypeMapper.SafeIdentifier(paramName)}");
                }
                if (!ok) {
                    skipped.Add($"method {TypeMapper.ShortMethod(m)}");
                    continue;
                }

                var ambiguous = arityGroups[(m.Name, m.Params.Count)] > 1;
                if (ambiguous && (m.IsStatic || !_o.ExactMethods)) {
                    skipped.Add($"method {TypeMapper.ShortMethod(m)} " +
                                "(overload: same name and arity" +
                                (m.IsStatic ? "; no static exact-call path" : "; pass --exact-methods") + ")");
                    continue;
                }
                var argumentNames = string.Join(", ", m.Params.Select(p => TypeMapper.SafeIdentifier(p.Name)));
                var argumentTypes = "{" + string.Join(", ", m.Params.Select(p => "\"" + Escape(p.Type.RuntimeName) + "\"")) + "}";
                var call = ambiguous
                    ? $"o.CallExact<{ret}>(\"{Escape(m.Name)}\", {argumentTypes}{(argumentNames.Length > 0 ? ", " + argumentNames : "")})"
                    : m.IsStatic
                        ? $"::URK::Unity::detail::InvokeStatic<{ret}>({refName}, \"{Escape(m.Name)}\"{(argumentNames.Length > 0 ? ", " + argumentNames : "")})"
                        : $"o.Call<{ret}>(\"{Escape(m.Name)}\"{(argumentNames.Length > 0 ? ", " + argumentNames : "")})";
                sb.AppendLine();
                sb.AppendLine($"    // method: {TypeMapper.ShortMethod(m)}{(m.IsStatic ? " (static)" : "")}");
                if (ambiguous)
                    sb.AppendLine($"    // overload resolved by parameter types: {argumentTypes}");
                sb.AppendLine(m.IsStatic
                    ? $"    static {ret} {member}({string.Join(", ", parameters)}) {{ return {call}; }}"
                    : $"    {ret} {member}({string.Join(", ", parameters)}) const {{ return {call}; }}");
                emitted++;

                var sampleArgs = string.Join(", ", m.Params.Select(p => {
                    var mapped = _map.Map(p.Type) ?? "void *";
                    return (mapped == "std::string" ? "std::string_view" : mapped) + "{}";
                }));
                _selfCheckCalls.Add(m.IsStatic
                    ? $"(void){wrapper}::{member}({sampleArgs});"
                    : $"(void){variable}.{member}({sampleArgs});");
            }
        }

        if (_o.Methods && t.Constructors.Count > 0 && !isUnityObject) {
            // UnityEngine.Object subclasses are left out on purpose: allocating them
            // with il2cpp_object_new gives a managed shell without a native object,
            // so those have to be created with Instantiate() or AddComponent().
            foreach (var ctor in t.Constructors) {
                var parameters = new List<string>();
                var ok = true;
                foreach (var (paramType, paramName) in ctor.Params) {
                    var mapped = _map.Map(paramType);
                    if (mapped is null) {
                        ok = false;
                        break;
                    }
                    parameters.Add($"{(mapped == "std::string" ? "std::string_view" : mapped)} {TypeMapper.SafeIdentifier(paramName)}");
                }
                if (!ok) {
                    skipped.Add($"constructor ({string.Join(", ", ctor.Params.Select(p => TypeMapper.ShortType(p.Type)))})");
                    continue;
                }
                var member = UniqueMember(usedNames, "New");
                var argumentNames = string.Join(", ", ctor.Params.Select(p => TypeMapper.SafeIdentifier(p.Name)));
                var argumentTypes = "{" + string.Join(", ", ctor.Params.Select(p => "\"" + Escape(p.Type.RuntimeName) + "\"")) + "}";
                sb.AppendLine();
                sb.AppendLine($"    // constructor: ({string.Join(", ", ctor.Params.Select(p => TypeMapper.ShortType(p.Type)))})");
                sb.AppendLine($"    static {wrapper} {member}({string.Join(", ", parameters)}) {{");
                sb.AppendLine($"        Object o = Object::New({refName});");
                if (ctor.Params.Count == 0)
                    sb.AppendLine("        o.Call<void>(\".ctor\");");
                else
                    sb.AppendLine($"        o.CallExact<void>(\".ctor\", {argumentTypes}, {argumentNames});");
                sb.AppendLine($"        return {wrapper}{{o}};");
                sb.AppendLine("    }");
                emitted++;

                var sampleArgs = string.Join(", ", ctor.Params.Select(p => {
                    var mapped = _map.Map(p.Type) ?? "void *";
                    return (mapped == "std::string" ? "std::string_view" : mapped) + "{}";
                }));
                _selfCheckCalls.Add($"(void){wrapper}::{member}({sampleArgs});");
            }
        }

        if (isUnityObject && _o.FindHelpers) {
            sb.AppendLine();
            sb.AppendLine("    // convenience lookups (UnityEngine.Object only)");
            sb.AppendLine($"    static {wrapper} Find() {{");
            sb.AppendLine($"        return {wrapper}{{Object::FindObjectOfType<Object>(\"{Escape(t.Image)}\", \"{Escape(t.Namespace)}\", \"{Escape(t.Name)}\")}};");
            sb.AppendLine("    }");
            sb.AppendLine($"    static std::vector<{wrapper}> FindAll() {{");
            sb.AppendLine($"        std::vector<{wrapper}> out;");
            sb.AppendLine($"        for (const Object &candidate : Object::FindObjectsOfType<Object>(\"{Escape(t.Image)}\", \"{Escape(t.Namespace)}\", \"{Escape(t.Name)}\"))");
            sb.AppendLine($"            out.push_back({wrapper}{{candidate}});");
            sb.AppendLine("        return out;");
            sb.AppendLine("    }");
            _selfCheckCalls.Add($"(void){wrapper}::Find();");
            _selfCheckCalls.Add($"(void){wrapper}::FindAll();");
        }

        sb.AppendLine("};");
        sb.AppendLine();

        _report.WriteLine($"{t.DisplayName}\timage={t.Image}\twrapper={wrapper}\temitted={emitted}\tskipped={skipped.Count}");
        foreach (var item in skipped)
            _report.WriteLine($"\tskip: {item}");
    }

    /// <summary>
    /// std::string reads use a managed-string codec; there is no matching
    /// write path for a raw std::string storage, so string setters are omitted.
    /// </summary>
    private static bool CanWriteCpp(string cpp) => cpp != "std::string";

    private static string UniqueMember(HashSet<string> used, string name) {
        var member = TypeMapper.SafeIdentifier(name);
        while (!used.Add(member))
            member += "_";
        return member;
    }

    private void EmitSelfCheck(StringBuilder sb) {
        if (!_o.SelfCheck || _selfCheckDecls.Count == 0)
            return;
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("// Compile-only instantiation of every generated accessor.");
        sb.AppendLine("// Build one TU with -DURTYPEGEN_SELF_CHECK to prove the header compiles.");
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("#if defined(URTYPEGEN_SELF_CHECK)");
        sb.AppendLine("namespace urtypegen_self_check {");
        sb.AppendLine("inline void run() {");
        foreach (var declaration in _selfCheckDecls)
            sb.AppendLine("    " + declaration);
        foreach (var call in _selfCheckCalls)
            sb.AppendLine("    " + call);
        sb.AppendLine("}");
        sb.AppendLine("} // namespace urtypegen_self_check");
        sb.AppendLine("#endif");
        sb.AppendLine();
    }
}
